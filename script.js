/* =========================================================
   ページ読み込み
   ========================================================= */

document.addEventListener("DOMContentLoaded", function () {

  loadHeader();

});


/* =========================================================
   ヘッダー読み込み
   ========================================================= */

function loadHeader() {

  const header =
    document.getElementById("header");


  /* header が存在しない場合 */
  if (!header) {

    return;

  }


  /* header.html を読み込む */

  fetch("header.html")

    .then(function (response) {

      /* 読み込みエラー確認 */

      if (!response.ok) {

        throw new Error(
          "header.html の読み込みに失敗しました。"
        );

      }


      return response.text();

    })


    .then(function (html) {

      /* -----------------------------------------
         header.html を表示
         ----------------------------------------- */

      header.innerHTML = html;


      /* -----------------------------------------
         言語ボタンを設定
         ----------------------------------------- */

      setupLanguageButtons();


      /* -----------------------------------------
         現在の言語を反映
         ----------------------------------------- */

      applyLanguage();


      /* -----------------------------------------
         footer.html を読み込む
         ----------------------------------------- */

      loadFooter();

    })


    .catch(function (error) {

      console.error(error);


      header.innerHTML =
        '<div class="load-error">' +
        'header.html を読み込めませんでした。' +
        '</div>';

    });

}


/* =========================================================
   フッター読み込み
   ========================================================= */

function loadFooter() {

  const footer =
    document.getElementById("footer");


  /* footer が存在しない場合 */

  if (!footer) {

    return;

  }


  /* footer.html を読み込む */

  fetch("footer.html")

    .then(function (response) {

      /* 読み込みエラー確認 */

      if (!response.ok) {

        throw new Error(
          "footer.html の読み込みに失敗しました。"
        );

      }


      return response.text();

    })


    .then(function (html) {

      /* -----------------------------------------
         footer.html を表示
         ----------------------------------------- */

      footer.innerHTML = html;


      /* -----------------------------------------
         現在の言語を反映
         ----------------------------------------- */

      applyLanguage();

    })


    .catch(function (error) {

      console.error(error);


      footer.innerHTML =
        '<div class="load-error">' +
        'footer.html を読み込めませんでした。' +
        '</div>';

    });

}


/* =========================================================
   言語切り替えボタン
   ========================================================= */

function setupLanguageButtons() {


  /* -----------------------------------------
     日本語・English ボタンを取得
     ----------------------------------------- */

  const buttons =
    document.querySelectorAll(".lang-btn");


  /* -----------------------------------------
     ボタンにクリックイベントを設定
     ----------------------------------------- */

  buttons.forEach(function (button) {


    button.addEventListener("click", function () {


      /* -----------------------------------------
         選択された言語を取得
         ----------------------------------------- */

      const lang =
        this.getAttribute("data-lang");


      /* -----------------------------------------
         言語を保存

         ja = 日本語
         en = English
         ----------------------------------------- */

      sessionStorage.setItem(
        "lang",
        lang
      );


      /* -----------------------------------------
         表示を切り替える
         ----------------------------------------- */

      applyLanguage();

    });

  });

}


/* =========================================================
   言語表示
   ========================================================= */

function applyLanguage() {


  /* =====================================================
     現在の言語を取得

     保存されていない場合は
     日本語を初期値にする
     ===================================================== */

  const lang =
    sessionStorage.getItem("lang") || "ja";


  /* =====================================================
     日本語コンテンツ
     ===================================================== */

  document
    .querySelectorAll(".ja")
    .forEach(function (element) {

      /*
       * 日本語を選択している場合
       * → 表示
       *
       * Englishを選択している場合
       * → 非表示
       */

      element.hidden =
        (lang !== "ja");

    });


  /* =====================================================
     英語コンテンツ
     ===================================================== */

  document
    .querySelectorAll(".en")
    .forEach(function (element) {

      /*
       * Englishを選択している場合
       * → 表示
       *
       * 日本語を選択している場合
       * → 非表示
       */

      element.hidden =
        (lang !== "en");

    });


  /* =====================================================
     注意

     .lang-btn はここでは操作しない。

     日本語ボタン・Englishボタンは
     常に両方表示する。

     ===================================================== */

}